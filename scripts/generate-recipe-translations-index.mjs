import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const translationsDirectory = join(repositoryRoot, "convex", "recipeTranslations", "recipes");
const outputPath = join(repositoryRoot, "convex", "recipeTranslations", "index.ts");
const filenames = readdirSync(translationsDirectory)
  .filter((filename) => filename.endsWith(".json"))
  .sort();

for (const filename of filenames) {
  const file = JSON.parse(readFileSync(join(translationsDirectory, filename), "utf8"));
  const expectedSlug = filename.replace(/\.json$/, "");
  if (file.slug !== expectedSlug) {
    throw new Error(`${filename} contains slug ${JSON.stringify(file.slug)} instead of ${expectedSlug}`);
  }
}

const imports = filenames.map(
  (filename, index) => `import translation${index} from ${JSON.stringify(`./recipes/${filename}`)};`,
);
const entries = filenames.map(
  (filename, index) => `  ${JSON.stringify(filename.replace(/\.json$/, ""))}: file(translation${index}),`,
);
const output = `// Generated by scripts/generate-recipe-translations-index.mjs. Do not edit.
import type { RecipeTranslationFile } from "../recipeLocales";
${imports.join("\n")}

// Shapes are checked field by field when translations are applied.
const file = (value: unknown) => value as RecipeTranslationFile;

export const recipeTranslationFiles: Record<string, RecipeTranslationFile> = {
${entries.join("\n")}
};
`;

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== output) {
    throw new Error("Recipe translations index is stale. Run npm run generate:recipe-translations-index.");
  }
} else {
  writeFileSync(outputPath, output);
}
