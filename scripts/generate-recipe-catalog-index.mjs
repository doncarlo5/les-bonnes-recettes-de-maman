import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const recipesDirectory = join(
  repositoryRoot,
  "convex",
  "recipeCatalog",
  "recipes",
);
const outputPath = join(
  repositoryRoot,
  "convex",
  "recipeCatalog",
  "rawCatalog.ts",
);
const filenames = readdirSync(recipesDirectory)
  .filter((filename) => filename.endsWith(".json"))
  .sort();

for (const filename of filenames) {
  const recipe = JSON.parse(
    readFileSync(join(recipesDirectory, filename), "utf8"),
  );
  const expectedSlug = filename.replace(/\.json$/, "");
  if (recipe.slug !== expectedSlug) {
    throw new Error(
      `${filename} contains slug ${JSON.stringify(recipe.slug)} instead of ${expectedSlug}`,
    );
  }
}

const imports = filenames.map(
  (filename, index) =>
    `import recipe${index} from ${JSON.stringify(`./recipes/${filename}`)};`,
);
const entries = filenames.map(
  (filename, index) =>
    `  ${JSON.stringify(filename.replace(/\.json$/, ""))}: {\n    sourcePath: ${JSON.stringify(`./recipes/${filename}`)},\n    recipe: recipe${index},\n  },`,
);
const output = `// Generated by scripts/generate-recipe-catalog-index.mjs. Do not edit.\n${imports.join("\n")}\n\nexport const rawRecipeCatalog = {\n${entries.join("\n")}\n} as const;\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== output) {
    throw new Error(
      "Recipe catalog index is stale. Run npm run generate:recipe-catalog-index.",
    );
  }
} else {
  writeFileSync(outputPath, output);
}
